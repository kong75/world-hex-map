import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const sourceRevision = 'f1890d9f152c896d250a77557a5751a93d494776';
const sourceUrl =
  `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${sourceRevision}` +
  '/geojson/ne_10m_land.geojson';

const columns = 72;
const rows = 47;
const north = 84;
const south = -58;
const columnDenominator = columns - 0.5;
const cellHalfLongitude = 180 / columnDenominator;
const cellHalfLatitude = (north - south) / (2 * (rows - 1));
const minimumCellLandCoverage = 0.3;
const minimumIslandCoverage = 0.04;
const minimumIslandArea = 0.12;
const minimumIslandSpan = 1.1;
const maximumIslandArea = 200;
const coverageSampleOffsets = createCoverageSampleOffsets();

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const dartOutputPath = path.resolve(
  scriptDirectory,
  '../lib/src/world_hex_grid_data.dart',
);
const typescriptOutputPath = path.resolve(
  scriptDirectory,
  '../typescript/src/world-hex-grid-data.ts',
);

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(
    `Unable to download Natural Earth land data (${response.status} ${response.statusText}).`,
  );
}

const geoJson = await response.json();
const polygons = extractPolygons(geoJson);
const cells = [];
const cellsByPolygon = Array.from({length: polygons.length}, () => []);

for (let row = 0; row < rows; row += 1) {
  for (let column = 0; column < columns; column += 1) {
    const center = normalizedCenter(row, column);
    const hex = logicalCellHex(center);
    const bounds = ringBounds(hex);
    const candidatePolygonIndexes = [];
    for (let polygonIndex = 0; polygonIndex < polygons.length; polygonIndex += 1) {
      const polygon = polygons[polygonIndex];
      if (!boundsOverlap(bounds, polygon)) continue;
      if (!polygonTouchesHex(polygon, hex)) continue;
      candidatePolygonIndexes.push(polygonIndex);
    }
    if (candidatePolygonIndexes.length === 0) continue;

    const cell = {
      id: row * columns + column,
      center,
      candidatePolygonIndexes,
      coverage: estimateLandCoverage(
        center,
        candidatePolygonIndexes.map((index) => polygons[index]),
      ),
    };
    cells.push(cell);
    for (const polygonIndex of candidatePolygonIndexes) {
      cellsByPolygon[polygonIndex].push(cell);
    }
  }
}

const selectedCellIds = new Set(
  cells
    .filter((cell) => cell.coverage >= minimumCellLandCoverage)
    .map((cell) => cell.id),
);
let preservedIslandCount = 0;

for (let polygonIndex = 0; polygonIndex < polygons.length; polygonIndex += 1) {
  const polygon = polygons[polygonIndex];
  if (!shouldPreserveIsland(polygon)) continue;

  let bestCell;
  let bestCoverage = 0;
  let represented = false;
  for (const cell of cellsByPolygon[polygonIndex]) {
    const coverage = estimatePolygonCoverage(cell.center, polygon);
    if (coverage > bestCoverage) {
      bestCell = cell;
      bestCoverage = coverage;
    }
    if (selectedCellIds.has(cell.id) && coverage >= minimumIslandCoverage) {
      represented = true;
      break;
    }
  }

  if (!represented && bestCell != null && bestCoverage >= minimumIslandCoverage) {
    selectedCellIds.add(bestCell.id);
    preservedIslandCount += 1;
  }
}

const landCellIds = [...selectedCellIds].sort((first, second) => first - second);
const rowsOfIds = [];
for (let index = 0; index < landCellIds.length; index += 12) {
  rowsOfIds.push(`    ${landCellIds.slice(index, index + 12).join(', ')},`);
}
const typescriptRowsOfIds = [];
for (let index = 0; index < landCellIds.length; index += 12) {
  typescriptRowsOfIds.push(
    `  ${landCellIds.slice(index, index + 12).join(', ')},`,
  );
}

const dartSource = `// GENERATED CODE - DO NOT EDIT.
// ignore_for_file: public_member_api_docs
//
// Generated by tool/generate_world_hex_grid.mjs from Natural Earth 1:10m
// land polygons at revision ${sourceRevision}.
// Cells use area-aware supersampling plus representative island preservation
// so narrow coasts survive without closing small sea channels.
// Natural Earth data is in the public domain.

abstract final class WorldHexGridData {
  static const int columns = ${columns};
  static const int rows = ${rows};
  static const double north = ${north}.0;
  static const double south = ${south}.0;

  static const List<int> landCellIds = <int>[
${rowsOfIds.join('\n')}
  ];
}
`;

const typescriptSource = `// GENERATED CODE - DO NOT EDIT.
//
// Generated by tool/generate_world_hex_grid.mjs from Natural Earth 1:10m
// land polygons at revision ${sourceRevision}.
// Cells use area-aware supersampling plus representative island preservation
// so narrow coasts survive without closing small sea channels.
// Natural Earth data is in the public domain.

export const columns = ${columns};
export const rows = ${rows};
export const north = ${north};
export const south = ${south};

export const landCellIds: readonly number[] = Object.freeze([
${typescriptRowsOfIds.join('\n')}
]);
`;

await mkdir(path.dirname(dartOutputPath), {recursive: true});
await mkdir(path.dirname(typescriptOutputPath), {recursive: true});
await Promise.all([
  writeFile(dartOutputPath, dartSource, 'utf8'),
  writeFile(typescriptOutputPath, typescriptSource, 'utf8'),
]);

const formatResult = process.platform === 'win32'
  ? spawnSync(`dart format "${dartOutputPath}"`, {
      encoding: 'utf8',
      shell: true,
      windowsHide: true,
    })
  : spawnSync('dart', ['format', dartOutputPath], {encoding: 'utf8'});
if (formatResult.status !== 0) {
  throw new Error(
    `Unable to format generated Dart data.\n${formatResult.stderr || formatResult.stdout}`,
  );
}

process.stdout.write(
  `Generated ${landCellIds.length} land cells (${preservedIslandCount} island rescues) at ` +
    `${path.relative(process.cwd(), dartOutputPath)} and ` +
    `${path.relative(process.cwd(), typescriptOutputPath)}\n`,
);

function normalizedCenter(row, column) {
  return {
    x: (column + (row % 2 === 1 ? 0.5 : 0)) / columnDenominator,
    y: row / (rows - 1),
  };
}

function createCoverageSampleOffsets() {
  const offsets = [];
  const divisions = 5;
  for (let row = -divisions; row <= divisions; row += 1) {
    for (let column = -divisions; column <= divisions; column += 1) {
      const y = row / divisions;
      const x = column / divisions;
      if (Math.abs(x) <= 1 - Math.abs(y) * 0.5 + 1e-10) {
        offsets.push([x, y]);
      }
    }
  }
  return offsets;
}

function estimateLandCoverage(center, candidatePolygons) {
  let landSamples = 0;
  const centerLongitude = center.x * 360 - 180;
  const centerLatitude = north - center.y * (north - south);
  for (const [x, y] of coverageSampleOffsets) {
    const longitude = centerLongitude + x * cellHalfLongitude;
    const latitude = centerLatitude - y * cellHalfLatitude;
    if (
      candidatePolygons.some((polygon) =>
        pointInPolygon(longitude, latitude, polygon),
      )
    ) {
      landSamples += 1;
    }
  }
  return landSamples / coverageSampleOffsets.length;
}

function estimatePolygonCoverage(center, polygon) {
  let landSamples = 0;
  const centerLongitude = center.x * 360 - 180;
  const centerLatitude = north - center.y * (north - south);
  for (const [x, y] of coverageSampleOffsets) {
    const longitude = centerLongitude + x * cellHalfLongitude;
    const latitude = centerLatitude - y * cellHalfLatitude;
    if (pointInPolygon(longitude, latitude, polygon)) landSamples += 1;
  }
  return landSamples / coverageSampleOffsets.length;
}

function shouldPreserveIsland(polygon) {
  if (polygon.projectedArea > maximumIslandArea) return false;
  return (
    polygon.projectedArea >= minimumIslandArea ||
    polygon.projectedSpan >= minimumIslandSpan
  );
}

function logicalCellHex(center) {
  const centerLongitude = center.x * 360 - 180;
  const centerLatitude = north - center.y * (north - south);
  return [
    [centerLongitude + cellHalfLongitude, centerLatitude],
    [
      centerLongitude + cellHalfLongitude / 2,
      centerLatitude - cellHalfLatitude,
    ],
    [
      centerLongitude - cellHalfLongitude / 2,
      centerLatitude - cellHalfLatitude,
    ],
    [centerLongitude - cellHalfLongitude, centerLatitude],
    [
      centerLongitude - cellHalfLongitude / 2,
      centerLatitude + cellHalfLatitude,
    ],
    [
      centerLongitude + cellHalfLongitude / 2,
      centerLatitude + cellHalfLatitude,
    ],
  ];
}

function polygonTouchesHex(polygon, hex) {
  if (
    hex.some(([longitude, latitude]) =>
      pointInPolygon(longitude, latitude, polygon),
    )
  ) {
    return true;
  }

  if (
    polygon.outer.some(([longitude, latitude]) =>
      pointInRing(longitude, latitude, hex),
    )
  ) {
    return true;
  }

  if (ringsIntersect(polygon.outer, hex)) return true;
  return polygon.holes.some((hole) => ringsIntersect(hole, hex));
}

function pointInPolygon(longitude, latitude, polygon) {
  if (!pointInRing(longitude, latitude, polygon.outer)) return false;
  return !polygon.holes.some((ring) =>
    pointInRing(longitude, latitude, ring),
  );
}

function ringsIntersect(first, second) {
  for (let firstIndex = 0; firstIndex < first.length; firstIndex += 1) {
    const firstStart = first[firstIndex];
    const firstEnd = first[(firstIndex + 1) % first.length];
    for (let secondIndex = 0; secondIndex < second.length; secondIndex += 1) {
      const secondStart = second[secondIndex];
      const secondEnd = second[(secondIndex + 1) % second.length];
      if (segmentsIntersect(firstStart, firstEnd, secondStart, secondEnd)) {
        return true;
      }
    }
  }
  return false;
}

function segmentsIntersect(firstStart, firstEnd, secondStart, secondEnd) {
  const firstOrientation = orientation(firstStart, firstEnd, secondStart);
  const secondOrientation = orientation(firstStart, firstEnd, secondEnd);
  const thirdOrientation = orientation(secondStart, secondEnd, firstStart);
  const fourthOrientation = orientation(secondStart, secondEnd, firstEnd);

  if (
    firstOrientation !== secondOrientation &&
    thirdOrientation !== fourthOrientation
  ) {
    return true;
  }

  return (
    (firstOrientation === 0 &&
      pointOnSegment(secondStart, firstStart, firstEnd)) ||
    (secondOrientation === 0 &&
      pointOnSegment(secondEnd, firstStart, firstEnd)) ||
    (thirdOrientation === 0 &&
      pointOnSegment(firstStart, secondStart, secondEnd)) ||
    (fourthOrientation === 0 &&
      pointOnSegment(firstEnd, secondStart, secondEnd))
  );
}

function orientation(start, end, point) {
  const crossProduct =
    (end[0] - start[0]) * (point[1] - start[1]) -
    (end[1] - start[1]) * (point[0] - start[0]);
  if (Math.abs(crossProduct) < 1e-10) return 0;
  return crossProduct > 0 ? 1 : -1;
}

function pointOnSegment(point, start, end) {
  const epsilon = 1e-10;
  return (
    point[0] >= Math.min(start[0], end[0]) - epsilon &&
    point[0] <= Math.max(start[0], end[0]) + epsilon &&
    point[1] >= Math.min(start[1], end[1]) - epsilon &&
    point[1] <= Math.max(start[1], end[1]) + epsilon
  );
}

function ringBounds(ring) {
  const longitudes = ring.map(([longitude]) => longitude);
  const latitudes = ring.map(([, latitude]) => latitude);
  return {
    minLongitude: Math.min(...longitudes),
    maxLongitude: Math.max(...longitudes),
    minLatitude: Math.min(...latitudes),
    maxLatitude: Math.max(...latitudes),
  };
}

function boundsOverlap(first, second) {
  return !(
    first.maxLongitude < second.minLongitude ||
    first.minLongitude > second.maxLongitude ||
    first.maxLatitude < second.minLatitude ||
    first.minLatitude > second.maxLatitude
  );
}

function pointInRing(longitude, latitude, ring) {
  let inside = false;
  for (
    let index = 0, previous = ring.length - 1;
    index < ring.length;
    previous = index++
  ) {
    const [x, y] = ring[index];
    const [previousX, previousY] = ring[previous];
    const crossesLatitude = y > latitude !== previousY > latitude;
    if (!crossesLatitude) continue;
    const crossingLongitude =
      ((previousX - x) * (latitude - y)) / (previousY - y) + x;
    if (longitude < crossingLongitude) inside = !inside;
  }
  return inside;
}

function extractPolygons(geoJson) {
  const result = [];
  for (const feature of geoJson.features ?? []) {
    addGeometry(feature.geometry, result);
  }
  if (result.length === 0) {
    throw new Error('Natural Earth GeoJSON contained no polygon geometry.');
  }
  return result;
}

function addGeometry(geometry, result) {
  if (!geometry) return;
  if (geometry.type === 'Polygon') {
    addPolygon(geometry.coordinates, result);
    return;
  }
  if (geometry.type === 'MultiPolygon') {
    for (const coordinates of geometry.coordinates) {
      addPolygon(coordinates, result);
    }
    return;
  }
  if (geometry.type === 'GeometryCollection') {
    for (const child of geometry.geometries ?? []) {
      addGeometry(child, result);
    }
  }
}

function addPolygon(coordinates, result) {
  if (!coordinates?.length || coordinates[0].length < 3) return;
  const outer = coordinates[0];
  const longitudes = outer.map(([longitude]) => longitude);
  const latitudes = outer.map(([, latitude]) => latitude);
  const centerLatitude =
    latitudes.reduce((sum, latitude) => sum + latitude, 0) / latitudes.length;
  const longitudeScale = Math.cos((centerLatitude * Math.PI) / 180);
  const outerArea = Math.abs(ringArea(outer));
  const holeArea = coordinates
    .slice(1)
    .reduce((sum, ring) => sum + Math.abs(ringArea(ring)), 0);
  const projectedArea = Math.max(0, outerArea - holeArea) * longitudeScale;
  const longitudeSpan =
    (Math.max(...longitudes) - Math.min(...longitudes)) * longitudeScale;
  const latitudeSpan = Math.max(...latitudes) - Math.min(...latitudes);
  result.push({
    outer,
    holes: coordinates.slice(1),
    minLongitude: Math.min(...longitudes),
    maxLongitude: Math.max(...longitudes),
    minLatitude: Math.min(...latitudes),
    maxLatitude: Math.max(...latitudes),
    projectedArea,
    projectedSpan: Math.max(longitudeSpan, latitudeSpan),
  });
}

function ringArea(ring) {
  let area = 0;
  for (
    let index = 0, previous = ring.length - 1;
    index < ring.length;
    previous = index++
  ) {
    area +=
      ring[previous][0] * ring[index][1] -
      ring[index][0] * ring[previous][1];
  }
  return area / 2;
}
